'use strict';
/*
 * eod/preopen.config.js —— 盘前选股（Pre-Open Screener）全部可调参数
 * ---------------------------------------------------------------------------
 * 设计原则与 tail.config.js 一致：纯数据、改参数不改代码、每个阈值写明口径。
 *
 * 与尾盘选股的区别（盘前特有的难点）：
 *   - 数据窗口只有 9:15–9:30 的「集合竞价」，价格字段用 今开(open) 近似竞价撮合价；
 *     9:20 后不可撤单段才可靠，故运行窗口设为 09:20–09:35（open 在 9:25 撮合后固定）。
 *   - 趋势 / 昨日涨幅无法从竞价快照得到，必须依赖「前一日 K 线」——由 baseline 提供
 *     （观察池实时抓 K 线算，全市场用隔夜缓存 baseline-YYYYMMDD.json）。
 *   - 「预期」锚定 = 昨日强度（昨日涨幅）+ 板块强度，纯数据可自动化，不碰消息面。
 *
 * 数据源（复用现有）：
 *   - 竞价快照：腾讯 qt.gtimg.cn 批量报价（open/现价/成交量/昨收）
 *   - 历史 K 线：腾讯 ifzq fqkline（前复权），与 gen_candidates.js 同链
 * ---------------------------------------------------------------------------
 */

// 复用尾盘的代码段定义（盲扫枚举用，避免两处维护）
const TAIL = require('./tail.config');

module.exports = {
  version: 1,

  // =========================================================================
  // 1. 交易时段（盘前集合竞价窗口）
  // =========================================================================
  session: {
    // 可运行的最早时点：9:20 后不可撤单段数据才可靠（9:15–9:20 可撤单噪声大）
    openFrom: '09:20',
    // 最晚时点：9:35 留 5 分钟宽限（open 在 9:25 撮合后即固定，9:25–9:35 抓到的 open 一致）
    openTo: '09:35',
    // 锚定日 = 最近一个已收盘交易日（lastClosedTradingDay），K 线取至此日
  },

  // =========================================================================
  // 2. 行情抓取（竞价快照）
  // =========================================================================
  market: {
    batch: 60,            // 与尾盘一致
    concurrency: 6,
    retries: 4,
    timeoutMs: 15000,
    ranges: TAIL.market.ranges,   // 复用：沪主板/科创/深主/创业/北交所
    excludePrefixes: ['sh900', 'sz200'],
    // 观察池模式数量小，红线可低；全市场模式应 >= 3000
    minValidQuotes: 50,
    staleMinutes: 45,
  },

  // =========================================================================
  // 3. 范围
  //    default: 'universe'（默认，全市场盲扫，覆盖最全、信号最准；需 baseline 缓存，见 baseline 段）
  //         可显式 --scope watchlist 回退到观察池（扫 candidates.json，轻量稳、不依赖缓存）
  //    生效优先级：--scope <x> 显式指定 > --universe 简写 > scope.default
  // =========================================================================
  scope: {
    default: 'universe',
  },

  // =========================================================================
  // 4. 基线（前一日 K 线指标缓存）—— P02/P03 的数据源
  // =========================================================================
  baseline: {
    dataDir: 'data',
    // 缓存文件名模板（按交易日）：preopen-baseline-YYYYMMDD.json
    fileName: (date) => `preopen-baseline-${date}.json`,
    // 全市场模式若缓存缺失则实时算（慢，~3min）；观察池模式默认实时算（几百只，~30s）
    computeIfMissing: true,
  },

  // =========================================================================
  // 5. 信号阈值（P01 竞价强势 / P02 弱转强 / P03 趋势）
  // =========================================================================
  rules: {
    // ---- P01 竞价强势 ----
    p1: {
      // 竞价涨幅（今开 vs 昨收）"高开"起点（%）；低于此不算强势开盘
      auctionChgMin: 3.0,
      // 近一字 / 涨停竞价（%）：达到即封板预期
      auctionChgLimit: 9.0,
      // 竞价量能比下限 = 竞价成交量 / 昨日全天成交量（无单位，同口径）。
      // 强竞价常见 3%–10%；低于 2% 视为缩量高开、动能不足。
      auctionVolRatioMin: 0.02,
      // 竞价量能比满分线（%）：达到即量能充沛
      auctionVolRatioFull: 0.08,
    },
    // ---- P02 弱转强 / 超预期（前几日大涨 + 今日开盘符合或超预期）----
    p2: {
      // 昨日"强势"门槛：≥7% 视为大涨，≥9.5% 视为涨停
      yesterdayStrong: 7.0,
      yesterdayLimit: 9.5,
      // 今日竞价高开"符合预期"区间（%）
      expectLow: 3.0,
      expectHigh: 7.0,
      // "超预期"门槛（%）：高开超过此值且昨日强 → 弱转强超预期
      exceed: 7.0,
    },
    // ---- P03 趋势跟踪（最近走趋势）----
    p3: {
      maPeriods: [5, 10, 20, 60],   // 均线周期
      // 20 日新高 / 60 日新高判定用
      highLookback: { d20: 20, d60: 60 },
      // 斜率门槛：近 20 日收盘价线性回归斜率（%/日）超过此值视为上行趋势
      slopeMinPerDay: 0.4,
      // 斜率满分线（%/日）
      slopeFullPerDay: 1.2,
    },
  },

  // =========================================================================
  // 6. 综合打分（总分 100，三项可解释）
  // =========================================================================
  score: {
    weights: {
      p1: 35,    // 竞价强势
      p2: 35,    // 弱转强 / 超预期
      p3: 30,    // 趋势跟踪
    },
    // 候选入选总分下限（低于此不进报告）
    minTotal: 45,
  },

  // =========================================================================
  // 7. 排除项（不可买 / 噪声过大）
  // =========================================================================
  exclude: {
    st: true,
    suspended: true,     // 停牌（成交量 0 或时间戳停在 09:00:00）
    oneWordBoard: false, // 盘前不剔一字板：一字涨停本身是强信号，留待 P1 标记
    newListing: true,
    newListingDays: 20,
  },

  // =========================================================================
  // 8. 分组与呈现
  // =========================================================================
  group: {
    source: 'industry-map',  // 复用 industry-map 缓存（build_industry_map.js 生成）
    maxPerGroup: 3,
    topN: 15,
    unknownLabel: '未分类',
  },

  // =========================================================================
  // 9. 落库与报告
  // =========================================================================
  store: {
    dataDir: 'data',
    reportDir: 'reports',
    prefix: 'preopen',         // 文件名前缀：preopen-YYYYMMDD.json / .html
    keepRunHistory: 20,
  },

  // =========================================================================
  // 10. 报告
  // =========================================================================
  report: {
    title: '盘前选股',
    titleEn: 'Pre-Open Screener',
    maxRows: 60,
    showDataGap: true,
  },

  // =========================================================================
  // 11. 通知（复用 notify.js：微信 + 163 邮箱）
  // =========================================================================
  notify: {
    enabled: true,
    topInMessage: 8,
    alertOnFailure: true,
  },

  // =========================================================================
  // 12. 收盘回填（溯源增强，Q3）
  // =========================================================================
  backfill: {
    // 回填运行窗口：收盘后 15:00 – 当日 23:59（quote 收盘后即返回当日终值，当晚随时可补；跨夜用 --date --force）
    from: '15:00',
    to: '23:59',
    // 命中定义：开盘价买入，当日收盘涨幅 ≥ 该值视为"开盘信号有效"（%）
    hitDayChgMin: 2.0,
  },
};
