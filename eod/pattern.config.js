  // =========================================================================
  // 3. 两阶段漏斗之「粗筛」
  //    只排除明确不可能的标的，不按成交额/涨幅取 TopN —— 形态票常处于缩量整理，
  //    按活跃度排序会把「启动后横住」的票全部误杀（实测两类模板均属此列）。
  //    命中票的 K 线才是主成本，故粗筛门槛刻意宽松、宁可多抓不可漏。
  // =========================================================================
  funnel: {
    minPrice: 2,
    maxPrice: 300,
    minTotalCapYi: 10,
    maxTotalCapYi: 2000,
    minTurnoverPct: 0.5,        // 报价 idx38；排除僵尸股
    minVolRatio: 0.3,
    minAmountWan: 500,          // 当日成交额下限（万元）
    maxCandidates: 0,           // 0 = 不截断；调试用 --limit N 覆盖
  },

  // =========================================================================
  // 4. 日 K 线（前复权，复用 market.fetchKline）
  //    健康度闸门：失败率超过红线即中止，绝不产出「今日 0 命中」的假报告。
  // =========================================================================
  kline: {
    concurrency: 6,
    minBars: 70,                // 老鸭头/VCP 需要 60 日均线，不足直接记缺口
    maxFailRate: 0.2,
    progressEvery: 500,
    cache: true,                // 日档缓存 kline-*.json；同日重跑零请求
  },

  // =========================================================================
  // 5. 排除项
  // =========================================================================
  exclude: {
    st: true,
    suspended: true,
    newListing: true,
    newListingDays: 30,
  },

  // =========================================================================
  // 6. 入选与展示
  // =========================================================================
  score: {
    minMatch: 62,               // 形态匹配分下限（0–100）
    maxRows: 0,                 // 报告行数上限；0 = 全量
    nearMissBand: 12,           // 贴线样本：落在入选线下 N 分内
  },

  // =========================================================================
  // 7. 参考价位（量化参考位，非投资建议）
  //    支撑位 = max(窗口内最低收盘, MA20)，且不得高于现价 ×0.98（避免倒挂）
  //    买入区间 = [支撑位, 现价 ×(1+chasePct%)]；现价距支撑过远 → 标「等回踩」
  //    止损 = 支撑位 ×(1-stopBufferPct%)；止盈 = 现价 +(现价-止损) × rewardRatio
  // =========================================================================
  price: {
    chasePct: 2.0,
    stopBufferPct: 2.0,
    rewardRatio: 2.0,
    maxChasePct: 8.0,
  },

  // =========================================================================
  // 8. 形态定义文件（唯一裁决方）
  //    包内默认定义 + 工作目录覆盖（覆盖文件存在则整份替换，便于不改包加形态）
  // =========================================================================
  templates: {
    file: 'pattern.templates.json',              // 相对 eod/（代码资产）
    overrideFile: 'data/pattern-templates.json', // 相对 eod/（工作目录资产）
  },

  // =========================================================================
  // 9. 归档与报告
  // =========================================================================
